"""Offline S3 signing and transport boundary tests; no bucket or credentials.

The fixed signing vectors use AWS's published example access/secret key pair,
an explicitly written canonical request, and R2's ``auto`` signing region.
The expected digests and signatures are literals derived independently of
R2Store. Mock openers consume file streams without making network requests.
"""

from datetime import datetime, timezone
from email.message import Message
import hashlib
import hmac
import importlib.util
import io
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
import urllib.error
from urllib.response import addinfourl


SPEC = importlib.util.spec_from_file_location("agent_r2_publisher", Path(__file__).with_name("publisher.py"))
publisher = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(publisher)

ENDPOINT = "https://example.r2.cloudflarestorage.com"
ACCESS_KEY = "AKIDEXAMPLE"
SECRET_KEY = "wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY"
KEY = "stable/releases/0.0.2/agent.app.tar.gz"
PAYLOAD = b"test payload"
PAYLOAD_SHA = "813ca5285c28ccee5cab8b10ebda9c908fd6d78ed9dc94cc65ea6cb67a7f13ae"
FIXED_TIME = datetime(2026, 10, 22, 3, 4, 5, tzinfo=timezone.utc)
CANONICAL_CREATE = (
    "PUT\n/agent-updates/stable/releases/0.0.2/agent.app.tar.gz\n\n"
    "content-length:12\n"
    "content-type:application/octet-stream\n"
    "host:example.r2.cloudflarestorage.com\n"
    "if-none-match:*\n"
    "x-amz-content-sha256:813ca5285c28ccee5cab8b10ebda9c908fd6d78ed9dc94cc65ea6cb67a7f13ae\n"
    "x-amz-date:20261022T030405Z\n\n"
    "content-length;content-type;host;if-none-match;x-amz-content-sha256;x-amz-date\n"
    "813ca5285c28ccee5cab8b10ebda9c908fd6d78ed9dc94cc65ea6cb67a7f13ae"
)
CREATE_CANONICAL_SHA = "b862834295f34ed57bb95db458cb4798c77e2f103834662c801972ff78d52f06"
CREATE_SIGNATURE = "f4bdc56620f024468268b63c28ce74c623374223950021e28dca54adae79565a"


class Response(io.BytesIO):
    def __init__(self, data=b"", headers=None):
        super().__init__(data)
        self.headers = headers or {}
        self.read_sizes = []
        self.bytes_read = 0

    def read(self, size=-1):
        self.read_sizes.append(size)
        data = super().read(size)
        self.bytes_read += len(data)
        return data


class OfflineOpener:
    """Always intercept requests, including when an assertion fails."""

    def __init__(self):
        self.requests = []
        self.responses = []
        self.error = None
        self.capture = None

    def open(self, request, timeout):
        self.requests.append((request, timeout))
        if self.error is not None:
            raise self.error
        if self.capture is not None:
            self.capture(request)
        return self.responses.pop(0) if self.responses else Response()


def headers(request):
    return {name.lower(): value for name, value in request.header_items()}


class R2StoreTests(unittest.TestCase):
    def setUp(self):
        self.opener = OfflineOpener()
        self.opener_factory = self.enterContext(patch.object(publisher.urllib.request, "build_opener", return_value=self.opener))
        self.clock = self.enterContext(patch.object(publisher, "datetime"))
        self.clock.now.return_value = FIXED_TIME
        self.store = publisher.R2Store(ENDPOINT, "agent-updates", ACCESS_KEY, SECRET_KEY)

    def test_fixed_create_only_sigv4_vector(self):
        # Capture the actual final string-to-sign as well as the wire header.
        # Expectations are fixed, not generated by the production signer.
        original_hmac = hmac.new
        with patch.object(publisher.hmac, "new", wraps=original_hmac) as signer:
            self.store.put(KEY, PAYLOAD, condition=("If-None-Match", "*"))
        request, timeout = self.opener.requests[0]
        actual = headers(request)
        self.assertEqual(hashlib.sha256(CANONICAL_CREATE.encode()).hexdigest(), CREATE_CANONICAL_SHA)
        self.assertEqual(signer.call_args.args[1], (
            "AWS4-HMAC-SHA256\n20261022T030405Z\n20261022/auto/s3/aws4_request\n" + CREATE_CANONICAL_SHA
        ).encode())
        self.assertEqual(actual["authorization"], (
            "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20261022/auto/s3/aws4_request, "
            "SignedHeaders=content-length;content-type;host;if-none-match;x-amz-content-sha256;x-amz-date, "
            "Signature=" + CREATE_SIGNATURE
        ))
        self.assertEqual(actual["if-none-match"], "*")
        self.assertEqual(actual["x-amz-content-sha256"], PAYLOAD_SHA)
        self.assertEqual(actual["content-length"], "12")
        self.assertEqual(request.full_url, ENDPOINT + "/agent-updates/" + KEY)
        self.assertEqual(request.get_method(), "PUT")
        self.assertEqual(request.data, PAYLOAD)
        self.assertEqual(timeout, 120)
        self.clock.now.assert_called_once_with(timezone.utc)

    def test_fixed_pointer_compare_and_swap_sigv4_vector(self):
        self.store.put("stable/latest.json", PAYLOAD, condition=("If-Match", '"old-etag"'), content_type="application/json")
        actual = headers(self.opener.requests[0][0])
        self.assertEqual(actual["if-match"], '"old-etag"')
        self.assertNotIn("if-none-match", actual)
        self.assertEqual(actual["authorization"], (
            "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20261022/auto/s3/aws4_request, "
            "SignedHeaders=content-length;content-type;host;if-match;x-amz-content-sha256;x-amz-date, "
            "Signature=dad3f950c5030af4557aa5a4c05452af3d7351eeaf4f19898fb49e3e5342f462"
        ))

    def test_file_put_streams_signed_size_and_sha256(self):
        data = b"bounded offline upload\n" * 100000
        digest = hashlib.sha256(data).hexdigest()
        uploaded = bytearray()
        source = []

        def consume(request):
            self.assertNotIsInstance(request.data, (bytes, bytearray))
            source.append(request.data)
            self.assertFalse(request.data.closed)
            while block := request.data.read(65536):
                uploaded.extend(block)

        self.opener.capture = consume
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / "agent.app.tar.gz"
            path.write_bytes(data)
            self.store.put(KEY, path, condition=("If-None-Match", "*"))
        actual = headers(self.opener.requests[0][0])
        self.assertEqual(uploaded, data)
        self.assertTrue(source[0].closed)
        self.assertEqual(actual["content-length"], str(len(data)))
        self.assertEqual(actual["x-amz-content-sha256"], digest)
        self.assertIn("content-length;content-type;host;if-none-match;x-amz-content-sha256;x-amz-date", actual["authorization"])

    def test_get_preserves_quoted_etag_case_insensitively(self):
        response = Response(PAYLOAD, {"eTaG": '"opaque-multipart-3"'})
        self.opener.responses.append(response)
        self.assertEqual(self.store.get(KEY), (PAYLOAD, '"opaque-multipart-3"'))
        request, _ = self.opener.requests[0]
        self.assertEqual(request.get_method(), "GET")
        self.assertIsNone(request.data)
        self.assertEqual(headers(request)["x-amz-content-sha256"], hashlib.sha256(b"").hexdigest())
        self.assertTrue(response.closed)

    def test_get_rejects_missing_or_oversized_etag(self):
        for response_headers in ({}, {"ETag": "x" * 256}):
            with self.subTest(headers=response_headers):
                self.opener.responses.append(Response(PAYLOAD, response_headers))
                with self.assertRaisesRegex(publisher.PublishError, "no valid ETag"):
                    self.store.get(KEY)

    def test_head_returns_headers_without_reading_a_body(self):
        response = Response(b"body must never be read", {"Content-Length": "999999999"})
        self.opener.responses.append(response)
        self.assertEqual(self.store.request("HEAD", KEY, maximum=1), (b"", {"Content-Length": "999999999"}))
        self.assertEqual(self.opener.requests[0][0].get_method(), "HEAD")
        self.assertEqual(response.read_sizes, [])
        self.assertTrue(response.closed)

    def test_buffered_response_is_bounded_and_closed(self):
        response = Response(b"1234567890", {"ETag": '"version"'})
        self.opener.responses.append(response)
        with self.assertRaisesRegex(publisher.PublishError, "oversized R2 response"):
            self.store.get(KEY, maximum=4)
        self.assertEqual(response.read_sizes, [5])
        self.assertEqual(response.bytes_read, 5)
        self.assertTrue(response.closed)

    def test_stream_hash_accepts_exact_bound_without_buffering_entire_object(self):
        data = b"large fixture\n" * 170000
        response = Response(data)
        self.opener.responses.append(response)
        self.assertEqual(self.store.stream_hash(KEY, maximum=len(data)), (hashlib.sha256(data).hexdigest(), len(data)))
        self.assertGreater(len(response.read_sizes), 2)
        self.assertTrue(all(0 < size <= publisher.CHUNK for size in response.read_sizes))
        self.assertTrue(response.closed)

    def test_stream_hash_stops_after_one_byte_beyond_bound(self):
        response = Response(b"0123456789" * 100)
        self.opener.responses.append(response)
        with self.assertRaisesRegex(publisher.PublishError, "oversized artifact"):
            self.store.stream_hash(KEY, maximum=7)
        self.assertEqual(response.read_sizes, [8])
        self.assertEqual(response.bytes_read, 8)
        self.assertTrue(response.closed)

    def test_get_and_same_treat_only_http_404_as_missing(self):
        self.opener.error = urllib.error.HTTPError(ENDPOINT, 404, "not found", {}, None)
        self.assertIsNone(self.store.get(KEY))
        self.assertFalse(self.store.same(KEY, PAYLOAD_SHA, len(PAYLOAD)))
        with self.assertRaises(publisher.StoreError) as raised:
            self.store.request("HEAD", KEY)
        self.assertEqual(raised.exception.status, 404)

    def test_http_conflict_and_forbidden_preserve_status_without_error_body(self):
        for status in (412, 403):
            with self.subTest(status=status):
                self.opener.error = urllib.error.HTTPError(ENDPOINT, status, "private upstream diagnostic", {}, None)
                with self.assertRaises(publisher.StoreError) as raised:
                    self.store.put(KEY, PAYLOAD, condition=("If-None-Match", "*"))
                self.assertEqual(raised.exception.status, status)
                self.assertEqual(str(raised.exception), f"R2 request failed (HTTP {status})")
                with self.assertRaises(publisher.StoreError) as raised:
                    self.store.get(KEY)
                self.assertEqual(raised.exception.status, status)

    def test_transport_errors_are_bounded_and_do_not_expose_upstream_diagnostics(self):
        for error in (OSError("private path or credential"), urllib.error.URLError("private upstream URL")):
            with self.subTest(error=type(error).__name__):
                self.opener.error = error
                with self.assertRaises(publisher.PublishError) as raised:
                    self.store.get(KEY)
                self.assertEqual(str(raised.exception), "R2 transport failed")

    def test_redirect_handler_refuses_following_all_supported_redirects(self):
        handler = self.opener_factory.call_args.args[0]
        if isinstance(handler, type):
            handler = handler()
        self.assertIsInstance(handler, publisher.NoRedirect)
        for status in (301, 302, 303, 307, 308):
            with self.subTest(status=status):
                requests = []

                class OfflineHTTPS(publisher.urllib.request.BaseHandler):
                    def https_open(self, request):
                        requests.append(request.full_url)
                        response_headers = Message()
                        response_headers["Location"] = "https://other.example/secret"
                        response = addinfourl(io.BytesIO(b""), response_headers, request.full_url, status)
                        response.msg = "Redirect"
                        return response

                # Exercise urllib's real redirect/error processing. There is
                # no network-capable handler in this director, even on failure.
                opener = publisher.urllib.request.OpenerDirector()
                for component in (OfflineHTTPS(), handler, publisher.urllib.request.HTTPErrorProcessor(), publisher.urllib.request.HTTPDefaultErrorHandler()):
                    opener.add_handler(component)
                self.store.opener = opener
                with self.assertRaises(publisher.StoreError) as raised:
                    self.store.get(KEY)
                self.assertEqual(raised.exception.status, status)
                self.assertEqual(requests, [ENDPOINT + "/agent-updates/" + KEY])

    def test_invalid_object_keys_never_reach_transport(self):
        for key in ("/absolute", "stable//latest.json", "../secret", "stable/%2fsecret", "stable/key?query", "stable/key#fragment"):
            with self.subTest(key=key), self.assertRaisesRegex(publisher.PublishError, "invalid R2 object key"):
                self.store.get(key)
        self.assertEqual(self.opener.requests, [])


